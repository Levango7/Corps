-- ============================================================================
-- decisions.reviewed_at：人工「已复盘」时间戳（#48）
--
-- 为什么是列而不是推导：复盘率要进决策漏斗的分子，分子必须来自人的明确宣告。
-- 用"打开详情停留 N 秒"这类隐式信号，会同时污染当期的定义与将来的历史——
-- 换口径时旧数据不可再解释，且无法审计。
--
-- 为什么 nullable 无默认值：存量决策一律视为"未复盘"（NULL），不做 backfill；
-- 语义上新加一列等于"此前没人宣告过复盘"，这比补一个假时间戳诚实。
--
-- 语义边界：编辑决策（PATCH .../decisions/{did}）会把该列清空 —— 内容变了，
-- 上一次复盘不再覆盖新版本。
--
-- 为什么不在本迁移里加 reviewed_by：复盘者身份由 analytics 事件
-- `decision_reviewed` 与审计日志承载，落列会造出第二个事实源。
-- 若将来 UI 需要在列表里显示"谁复盘"，再加列并 backfill 是可逆的。
-- ============================================================================

-- AlterTable
ALTER TABLE "decisions" ADD COLUMN "reviewed_at" TIMESTAMPTZ;
