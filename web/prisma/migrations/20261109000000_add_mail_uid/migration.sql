-- ============================================================================
-- mails.uid：IMAP 邮箱内 UID，增量同步的游标
--
-- 为什么必须落列：增量同步要知道"上次同步到哪一封"。IMAP 的 UID 在邮箱内
-- 单调递增且跨连接稳定（UIDVALIDITY 不变的前提下），是唯一可靠的游标；
-- 用 sentAt 当游标会在"同一秒多封"和"服务器时钟偏移"两处失准。
--
-- 为什么 nullable：非 IMAP 来源（如手动录入、其它协议）没有 UID，
-- 留 null 而不是填 0——0 会被误读成"第一封"。
-- ============================================================================

-- AlterTable
ALTER TABLE "mails" ADD COLUMN "uid" INTEGER;
