// 追问建议 prompt 模板——根据用户问题 + AI 回答生成 3 个后续追问建议。
//
// 设计要点：
// - 输出严格 JSON 数组格式（["问题1", "问题2", "问题3"]），便于后端 JSON.parse
// - 含 few-shot 示例引导模型输出格式
// - 追问应与当前问答相关、有深度、帮助用户深入探索话题
// - 中文输出

/**
 * 追问建议系统 prompt：定义 AI 角色、任务与输出格式。
 */
export function buildFollowUpSystemPrompt(): string {
  return `你是企业知识助手的追问建议生成器。
根据用户的问题和 AI 的回答，生成 3 个有价值的后续追问建议。

生成规则：
1. 追问应与当前问答内容直接相关，帮助用户深入探索话题
2. 追问应具有实际价值，能引出更有用的信息（而非简单确认）
3. 追问应简洁明了，每个不超过 50 个字符
4. 生成恰好 3 个追问，不多不少
5. 中文输出
6. 输出严格的 JSON 数组格式，不要包含任何其他文本
7. 仅基于问答内容生成追问，不要编造未提及的信息

## 推理步骤
1. 分析用户问题的核心意图
2. 回顾回答中提供的关键信息
3. 确定用户可能想进一步了解的方向
4. 生成 3 个追问建议，确保覆盖不同角度

## 输出格式
输出一个 JSON 字符串数组，包含 3 个追问建议：
["追问1", "追问2", "追问3"]

## 示例

### 示例 1
用户问题：本周有哪些进行中的任务？
AI 回答：本周进行中的任务共 2 项：需求评审（进行中）和接口联调（进行中）。
输出：
["需求评审的负责人是谁？", "这两个任务的截止日期是什么时候？", "有没有阻塞的任务需要关注？"]

### 示例 2
用户问题：今天有哪些会议？
AI 回答：今天有 2 个会议：10:00 产品评审会、14:00 技术方案讨论会。
输出：
["产品评审会的参会人员有哪些？", "技术方案讨论会的议题是什么？", "这两个会议有相关的待办事项吗？"]

### 示例 3
用户问题：OKR 进度如何？
AI 回答：当前 Q1 OKR 整体进度 65%，其中关键结果 KR1 已完成、KR2 进行中（80%）、KR3 风险中（30%）。
输出：
["KR3 风险中的具体原因是什么？", "KR2 预计什么时候能完成？", "有哪些措施可以推进 KR3？"]`;
}

/**
 * 追问建议用户 prompt：拼接用户问题与 AI 回答。
 *
 * @param question 用户原始问题
 * @param answer AI 的回答内容
 */
export function buildFollowUpUserPrompt(question: string, answer: string): string {
  // P2-5: 截断过长的 question 和 answer，避免超出模型上下文窗口
  const truncatedQuestion = question.length > 1000 ? question.slice(0, 1000) + "\n\n[问题已截断]" : question;
  const truncatedAnswer = answer.length > 4000 ? answer.slice(0, 4000) + "\n\n[回答已截断]" : answer;
  return `## 用户问题
${truncatedQuestion}

## AI 回答
${truncatedAnswer}

请生成 3 个后续追问建议，输出 JSON 数组格式。`;
}